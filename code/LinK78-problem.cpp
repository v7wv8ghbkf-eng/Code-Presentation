#include<iostream>
using namespace std;

// 纭澶ц嚧鐨勬暟缁勮寖鍥达紝闃叉鏁扮粍澶皬銆佽竟鐣屽お绱т粠鑰屽彂鐢熻秺鐣?const int N = 35;

// 浜屽弶鏍戣妭鐐逛釜鏁?int n;
// w[i]绗琲涓妭鐐圭殑鍒嗘暟锛況oot[l][r]鍖洪棿[l,r]鏋勬垚瀛愭爲鏃跺緱鍒嗘渶楂樼殑鏍硅妭鐐圭紪鍙?int w[N], root[N][N];
/*-----鐘舵€佽〃绀篺[l][r]-----*/
// 銆愰泦鍚堛€戜腑搴忛亶鍘嗗尯闂碵l,r]鍐呯殑鑺傜偣鏋勬垚鐨勬墍鏈変簩鍙夋爲涓紝鏈€楂樺姞鍒?int f[N][N];

// 鍓嶅簭閬嶅巻杈撳嚭锛氭牴鎹畆oot鏁扮粍閫掑綊杈撳嚭浜屽弶鏍戠殑鍓嶅簭閬嶅巻
void dfs(int l, int r)
{
    // 绌哄尯闂达紝閫掑綊杈圭晫
    if(l > r) return;

    // 鍙栧嚭褰撳墠鍖洪棿鐨勬牴鑺傜偣缂栧彿
    int k = root[l][r];
    // 杈撳嚭鏍硅妭鐐癸紙鍓嶅簭閬嶅巻锛氭牴鈫掑乏鈫掑彸锛?    cout << k << " ";

    // 閫掑綊杈撳嚭宸﹀瓙鏍戝拰鍙冲瓙鏍?    dfs(l, k - 1);
    dfs(k + 1, r);
}

int main()
{
    // 杈撳叆鑺傜偣鏁板拰姣忎釜鑺傜偣鐨勫垎鏁帮紝涓嬫爣浠?寮€濮?    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> w[i];
    }

    /*----- 鍖洪棿DP锛氭灇涓惧尯闂撮暱搴︼紝鐢辩煭鍒伴暱閫掓帹 -----*/
    for(int len = 1; len <= n; len++)
    {
        // 鏋氫妇鍖洪棿宸︾鐐筶
        for(int l = 1; l + len - 1 <= n; l++)
        {
            // 鍖洪棿鍙崇鐐箁
            int r = l + len - 1;

            // 闀垮害涓?锛堝彾鑺傜偣锛夛細鍔犲垎灏辨槸鍙惰妭鐐规湰韬殑鍒嗘暟
            if(l == r)
            {
                f[l][r] = w[l];
                root[l][r] = l;
                continue;
            }

            // 鏋氫妇鏍硅妭鐐筴锛氬尯闂寸殑姣忎釜鑺傜偣閮藉彲鑳戒綔涓烘牴
            for(int k = l; k <= r; k++)
            {
                // 宸﹀瓙鏍戝姞鍒嗭細濡傛灉k鏄乏绔偣鍒欏乏瀛愭爲涓虹┖锛堣瀹氫负1锛?                int left = (k == l) ? 1 : f[l][k - 1];
                // 鍙冲瓙鏍戝姞鍒嗭細濡傛灉k鏄彸绔偣鍒欏彸瀛愭爲涓虹┖锛堣瀹氫负1锛?                int right = (k == r) ? 1 : f[k + 1][r];

                // 鍔犲垎璁＄畻鍏紡锛氬乏瀛愭爲鍔犲垎 脳 鍙冲瓙鏍戝姞鍒?+ 鏍硅妭鐐瑰垎鏁?                int score = left * right + w[k];

                // 涓ユ牸浣跨敤 < 鏉ユ洿鏂帮細淇濊瘉鍦ㄥ緱鍒嗙浉鍚屾椂淇濈暀鏇村皬鐨勬牴鑺傜偣缂栧彿
                // 杩欐牱鏈€缁堣緭鍑虹殑鏄瓧鍏稿簭鏈€灏忕殑鍓嶅簭閬嶅巻鏂规
                if(f[l][r] < score)
                {
                    f[l][r] = score;
                    root[l][r] = k;
                }
            }
        }
    }

    // 杈撳嚭鏈€楂樺姞鍒?    cout << f[1][n] << endl;
    // 杈撳嚭鍓嶅簭閬嶅巻锛堝瓧鍏稿簭鏈€灏忔柟妗堬級
    dfs(1, n);

    return 0;
}
