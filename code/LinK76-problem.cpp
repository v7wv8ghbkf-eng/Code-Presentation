#include<iostream>
using namespace std;

// 确认大致的数组范围，防止数组太小、边界太紧从而发生越界
const int N = 310;

// num堆石子
int num;
// w[i]第i堆石子的原始质量；s[i]前缀和（前i堆石子质量之和）
int w[N], s[N];
/*-----状态表示f[l][r]-----*/
// 【集合】将第l堆到第r堆石子合并成一堆的所有方案中，最小总代价
int f[N][N];

int main()
{
    // 输入石子堆数
    cin >> num;

    // 读入石子重量，同时计算前缀和
    // s[i] = 前i堆石子的总质量，用于O(1)计算区间和
    for(int i = 1; i <= num; i++)
    {
        cin >> w[i];
        s[i] = s[i - 1] + w[i];
    }

    /*----- 区间DP：枚举区间长度，由短到长递推 -----*/
    // 长度为1的区间不需要合并，代价自然为0（全局数组已初始化为0）
    for(int len = 2; len <= num; len++)
    {
        // 枚举区间左端点l
        for(int l = 1; l + len - 1 <= num; l++)
        {
            // 区间右端点r
            int r = l + len - 1;

            // 初始化为较大值，后续用min逐步更新
            f[l][r] = 1e9;

            // 枚举分界点k：将[l,r]分成[l,k]和[k+1,r]两部分
            // 先将左右两堆各自内部合并，再将这两堆合并在一起
            for(int k = l; k < r; k++)
            {
                // 状态转移：
                // 代价 = 左边合并的最小代价 + 右边合并的最小代价 + 本次合并的代价
                // 本次合并的代价 = [l,r]区间所有石子质量之和 = s[r] - s[l-1]
                f[l][r] = min(f[l][r],
                             f[l][k] + f[k + 1][r] + s[r] - s[l - 1]);
            }
        }
    }

    // 最终所需要的答案：
    // 将第1堆到第num堆全部石子合并成一堆的最小总代价
    cout << f[1][num] << endl;
    return 0;
}
