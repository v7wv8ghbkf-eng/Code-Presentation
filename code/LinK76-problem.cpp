#include<iostream>
using namespace std;

// 纭澶ц嚧鐨勬暟缁勮寖鍥达紝闃叉鏁扮粍澶皬銆佽竟鐣屽お绱т粠鑰屽彂鐢熻秺鐣?const int N = 310;

// num鍫嗙煶瀛?int num;
// w[i]绗琲鍫嗙煶瀛愮殑鍘熷璐ㄩ噺锛泂[i]鍓嶇紑鍜岋紙鍓峣鍫嗙煶瀛愯川閲忎箣鍜岋級
int w[N], s[N];
/*-----鐘舵€佽〃绀篺[l][r]-----*/
// 銆愰泦鍚堛€戝皢绗琹鍫嗗埌绗瑀鍫嗙煶瀛愬悎骞舵垚涓€鍫嗙殑鎵€鏈夋柟妗堜腑锛屾渶灏忔€讳唬浠?int f[N][N];

int main()
{
    // 杈撳叆鐭冲瓙鍫嗘暟
    cin >> num;

    // 璇诲叆鐭冲瓙閲嶉噺锛屽悓鏃惰绠楀墠缂€鍜?    // s[i] = 鍓峣鍫嗙煶瀛愮殑鎬昏川閲忥紝鐢ㄤ簬O(1)璁＄畻鍖洪棿鍜?    for(int i = 1; i <= num; i++)
    {
        cin >> w[i];
        s[i] = s[i - 1] + w[i];
    }

    /*----- 鍖洪棿DP锛氭灇涓惧尯闂撮暱搴︼紝鐢辩煭鍒伴暱閫掓帹 -----*/
    // 闀垮害涓?鐨勫尯闂翠笉闇€瑕佸悎骞讹紝浠ｄ环鑷劧涓?锛堝叏灞€鏁扮粍宸插垵濮嬪寲涓?锛?    for(int len = 2; len <= num; len++)
    {
        // 鏋氫妇鍖洪棿宸︾鐐筶
        for(int l = 1; l + len - 1 <= num; l++)
        {
            // 鍖洪棿鍙崇鐐箁
            int r = l + len - 1;

            // 鍒濆鍖栦负杈冨ぇ鍊硷紝鍚庣画鐢╩in閫愭鏇存柊
            f[l][r] = 1e9;

            // 鏋氫妇鍒嗙晫鐐筴锛氬皢[l,r]鍒嗘垚[l,k]鍜孾k+1,r]涓ら儴鍒?            // 鍏堝皢宸﹀彸涓ゅ爢鍚勮嚜鍐呴儴鍚堝苟锛屽啀灏嗚繖涓ゅ爢鍚堝苟鍦ㄤ竴璧?            for(int k = l; k < r; k++)
            {
                // 鐘舵€佽浆绉伙細
                // 浠ｄ环 = 宸﹁竟鍚堝苟鐨勬渶灏忎唬浠?+ 鍙宠竟鍚堝苟鐨勬渶灏忎唬浠?+ 鏈鍚堝苟鐨勪唬浠?                // 鏈鍚堝苟鐨勪唬浠?= [l,r]鍖洪棿鎵€鏈夌煶瀛愯川閲忎箣鍜?= s[r] - s[l-1]
                f[l][r] = min(f[l][r],
                             f[l][k] + f[k + 1][r] + s[r] - s[l - 1]);
            }
        }
    }

    // 鏈€缁堟墍闇€瑕佺殑绛旀锛?    // 灏嗙1鍫嗗埌绗琻um鍫嗗叏閮ㄧ煶瀛愬悎骞舵垚涓€鍫嗙殑鏈€灏忔€讳唬浠?    cout << f[1][num] << endl;
    return 0;
}
