#include<iostream>
#include<algorithm>
using namespace std;

// 确认大致的数组范围，防止数组太小、边界太紧从而发生越界
const int N = 110;

// n种物品，背包容量为V（数据范围 N,V,si ≤ 100）
int n, V;
// 第i种物品的：v体积 / w价值 / s数量(最多s件)
int v[N], w[N], s[N];
/*-----状态表示f[i][j]-----*/
// 【集合】对前i组物品、限定容量为j，所有可能的总价值
int f[N][N];

int main()
{
    // 输入并装填元素，从1开始方便下标观察
    cin >> n >> V;
    for(int i = 1; i <= n; i++)
    {
        cin >> v[i] >> w[i] >> s[i];
    }

    // 枚举物品种数与限定容量，都是由少到多枚举
    for(int i = 1; i <= n; i++)
    {
        for(int j = 0; j <= V; j++)
        {
            /*-----集合运算-----*/
            // 对前i种物品与限定容量j而言，枚举选取第i种物品的数量k
            // k=0表示不选第i种物品（等价于f[i-1][j]）
            // k从0到s[i]（且容量不能超）逐一遍历取最大值

            // f[i][j] 初始为不选的情况（k=0时自动覆盖）
            // 注意：这里利用max的累积比较，每次尝试不同k值并取最优
            for(int k = 0; k <= s[i] && j >= k * v[i]; k++)
            {
                // 选k个第i种物品：腾出k*v[i]容量，获得k*w[i]价值
                // 从 f[i-1][j - k*v[i]]（上一层）转移
                f[i][j] = max(f[i][j], f[i - 1][j - k * v[i]] + k * w[i]);
            }
        }
    }

    // 最终所需要的答案：
    // 是同时存在n种物品(每种有数量限制)时，限定(背包)总容量为V，所取得的总价值最大值
    cout << f[n][V] << endl;
    return 0;
}
