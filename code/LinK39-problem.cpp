/*-----题目分析-----
 * 净化迷雾森林：在H×W的迷宫中，林克从起点'@'出发，只能向上下左右
 * 四个方向移动到相邻的迷雾区域'.'（墙壁'#'不可通过）。
 * 求林克总共能净化多少区域（包括初始位置）。
 *
 * 本质：连通分量大小计算（Flood Fill / 洪水填充）。
 * 解法：DFS。每访问一个迷雾格子就标记为'#'（即已净化），
 *       递归统计所有可达的迷雾格子数量。
 * 时间复杂度：O(H×W)，每个格子最多被访问一次。
 *-----*/

#include <iostream>
using namespace std;

int H, W;
char forest[30][30];  // 迷宫地图，30×30可以容纳题目限制的20×20

// 四个方向的移动偏移量：右、下、上、左
int dx[4] = {0, 1, -1, 0}, dy[4] = {1, 0, 0, -1};

/*-----dfs函数分析-----
 * dfs(i, j)：从格子(i,j)出发，DFS统计能访问到的迷雾格子总数。
 *
 * 递归分解：
 * - 自身计入：res初始为1（当前格子）。
 * - 标记访问：将当前格子改为'#'，防止重复计数（Flood Fill的核心技巧：
 *   直接在原地图上修改，省去额外的visited数组）。
 * - 递归扩展：向四个方向尝试，对每个合法的相邻迷雾格子递归统计，
 *   将结果累加到res中。
 * - 返回：以(i,j)为根的连通分量总大小。
 *
 * 注意：该函数不回溯（不改回'.'），因为每个格子只需访问一次，
 *       标记为'#'后永久排除，符合连通分量计数的语义。
 *-----*/
int dfs(int i, int j)
{
    int res = 1;           // 计数：至少包含当前格子自身
    forest[i][j] = '#';    // 标记为已访问（已净化），防止走回头路

    for (int k = 0; k < 4; k++)  // 尝试四个方向
    {
        int x = i + dx[k], y = j + dy[k];
        // 边界检查 + 判断是否为可净化的迷雾区域
        if (x >= 0 && y >= 0 && x < H && y < W && forest[x][y] == '.')
        {
            res += dfs(x, y);  // 递归净化相邻区域，累加结果
        }
    }

    return res;
}

int main()
{
    int startX, startY;

    // 多组测试数据：当W和H均为0时结束输入
    while (cin >> W >> H, W || H)
    {
        // 读入地图，同时找到林克的起点位置'@'
        for (int i = 0; i < H; i++)
        {
            for (int j = 0; j < W; j++)
            {
                cin >> forest[i][j];
                if (forest[i][j] == '@')
                {
                    startX = i;
                    startY = j;
                }
            }
        }
        // 从起点开始DFS，统计可达的迷雾区域总数
        cout << dfs(startX, startY) << endl;
    }
    return 0;
}
