#include <climits>

using namespace std;

/*-----memo璁板繂鍖?----*/
// 璁板繂鍖栨槸鍓灊鐨勪竴鐜?
// memo浼氬瓨鍌ㄥ凡缁忕‘瀹氱殑dfs[w][h][m]
// 杩欐槸鍥犱负鍦ㄥw銆乭鐨勪笉鍚屽垏娉曚腑锛屾€讳細鍒囧嚭鏉ラ噸澶嶉潰瀵规煇涓暱瀹戒互鍙婃煇涓姹傚垏鍑哄潡鏁?
// 濡傛灉宸茬粡閫氳繃dfs寰楀埌杩囨煇涓猟fs鐨勭瓟妗堬紝閭ｄ箞鍙互涓嶉噸澶嶈绠?
int memo[25][25][25];

/*-----dfs鍑芥暟-----*/
// 瀵逛簬dfs鍑芥暟濡傛灉涓嶄粠閫掑綊鐨勬柟寮忓幓鐪嬩細濂界悊瑙ｄ竴浜?
// 涔熷氨鏄皢鍏剁函鍔熻兘鎬у鐞?dfs鏄疄鐜颁粈涔堝姛鑳界殑)锛?
// dfs(w, h, m)鏄敤鏉ヨ緭鍑哄皢闀夸负w銆佸涓篽鐨勮泲绯曞垏鍑烘潵鐨刴鍧楄泲绯曚腑锛岃泲绯曟渶澶ч潰绉殑涓嬮檺
// (杩欓噷鐗规畩鍦ㄦ湰棰樺彲浠ュ彧浣跨敤dfs杈撳嚭绛旀锛宒fs浣滀负鍑芥暟褰撶劧涔熷彲浠ュ彧瀹炵幇灞€閮ㄥ姛鑳?
int dfs(int w, int h, int m)
{
    // 濡傛灉鍙渶瑕佸垏鎴?鍧楋紝閭ｅ氨鏄泲绯曞潡鏈韩
    if (m == 1)
        return w * h;

    // memo瀵逛簬鏈悳绱㈢殑dfs缁勫悎涓?1
    // res(result,dfs鏈€缁堣緭鍑衡€滅粨鏋溾€?鏄紩鐢紝鐩稿綋浜庢槸绠€鍖栦簡memo鐨勫啑闀夸功鍐?
    int &res = memo[w][h][m];
    if (res != -1)
        return res;

    /*-----鍑芥暟涓讳綋鍔熻兘鍒嗘瀽-----*/
    // 瀵逛簬dfs[w][h][m]鑰岃█锛岃鍒掑垎浠诲姟銆佺粏鍒嗕笅鍘伙紝鍙栧喅浜庣涓€鍒€鐨勫垏娉?
    // 杩欎竴鍒€鍙互妯垏鎴栬€呯珫鍒囷紝骞朵互姝や负渚濇嵁鎶娾€滃垏鎴恗鍧椻€濈殑浠诲姟鍒嗛厤缁欏垏鍑烘潵鐨勯偅涓ゅ潡
    // 鐒跺悗鍐嶇户缁寜鐓т笉鍚屽垏娉曞垏涓嬪幓
    // 涓嶉渶瑕佺閫掑綊鏄粈涔堢粨鏋勶紝鍙叧娉ㄥ姛鑳芥湰韬殑瀹炵幇涓巇fs鍑芥暟鐨勭粨鍚堝嵆鍙?

    // best鏄渶鍚庢垜鍙栧埌鐨勭粨鏋?
    // 浠ラ槻绗竴娆est鍦╩in鏇存柊涓細閿欒瀵艰嚧鏃犳硶閫変腑寰楀嚭鐨勫€硷紝閫変釜杈冨ぇ鐨勬暟瀛?
    int best = INT_MAX;

    // 瀵规í鍒囷紝浼氬皢瀹絟鍒嗕负h1銆乭2锛岄偅涔堣繖閲屽彲浠ユ灇涓惧拰h1闀垮害
    for (int h1 = 1; h1 < h; h1++)
    {
        // 鍒囧嚭鏉ョ殑鍒嗗壊涓篽1 + h2 = h
        int h2 = h - h1;
        // 鏋氫妇鍒嗗壊缁檋1鐨勫潡鏁発锛岄偅涔堢粰h2鐨勫氨鏄痬 - k鍧楀槢
        for (int k = 1; k < m; k++)
        {
            // 瀵逛簬闀縲瀹絟鐨勮泲绯曚笖鍒囧嚭鏉ヨ竟闀夸负鏁存暟锛岀悊璁轰笂鍙兘鍒囨垚1x1鐨勫ぇ灏?
            // 涔熷氨鏄渶澶氬垏鎴恮 * h鍧?
            // 濡傛灉鍒嗛厤缁欐煇涓€杈圭殑鍧楁暟澶锛岄偅涔堣繖涓猭灏遍渶瑕佽璺宠繃
            if (k > h1 * w || m - k > h2 * w)
                continue;

            // 鏈杩欓噷鐨勫鐞嗗緢鍍廌P锛屽洜涓烘槸鍦ㄤ笉鏂紭鍖栧彇鏈€浼樿В锛屽啀鍦ㄦ渶浼樿В鐨勫熀纭€涓婃洿鏂?
            // 鍚屾椂涓嶄細鏈夊洖澶磋矾锛屽洜涓洪兘琚玬emo鐮嶆帀浜?
            int cur = max(dfs(w, h1, k), dfs(w, h2, m - k));
            best = min(best, cur);
        }
    }

    // 鎺ヤ笅鏉ュ氨鏄珫鐫€鍒?
    for (int w1 = 1; w1 < w; w1++)
    {
        int w2 = w - w1;
        for (int k = 1; k < m; k++)
        {
            if (k > w1 * h || m - k > w2 * h)
                continue;

            int cur = max(dfs(w1, h, k), dfs(w2, h, m - k));
            best = min(best, cur);
        }
    }

    // 鍦╞est瀵逛袱绉嶆柟妗堝垎鍒洿鏂拌繃鍚庯紝鍙互杈撳嚭浜?
    // 浣嗕篃涓嶈兘蹇樿瀵逛互w,h,m涓哄舰鍙傜殑dfs鍋歮emo璁板繂鍖栧偍瀛?
    return res = best;
}

int main()
{
    // 鍒濆鍖栬蹇嗗簱memo
    memset(memo, -1, sizeof(memo));

    int w, h, m;
    while (cin >> w >> h >> m)
    {
        // 澶氱粍杈撳叆鏁版嵁鐨勭粨鏉?
        if (w == 0 && h == 0 && m == 0)
            break;

        // 鍒嗗埆杈撳嚭鏁版嵁
        cout << dfs(w, h, m) << endl;
    }
    return 0;
}