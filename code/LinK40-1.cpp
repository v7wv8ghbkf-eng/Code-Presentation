/*-----题目分析-----
 * 骑士巡游问题（Knight's Tour）：在p×q的变形棋盘上，
 * 骑士按国际象棋马的走法（走"日"字，共8种），问是否能一次遍历
 * 所有格子恰好一次。若存在，输出字典序最小的完整路径；
 * 若不存在，输出"none"。
 *
 * 输出格式：每个格子用"大写字母+数字"表示，如A1、B3等。
 * 字母对应列（A=第0列），数字对应行（1=第0行）。
 *
 * 解法：DFS + 回溯。
 * 关键1：dx/dy数组的排列顺序决定了试探的字典序——按字典序
 *        排列移动方向，保证首次找到的完整路径即为字典序最小的解。
 * 关键2：DFS找到第一条完整路径即停止（剪枝），不再搜索其他路径。
 * 时间复杂度：最坏O(8^(p*q))，但实际由于约束和剪枝会大幅缩小。
 *-----*/

#include<cstring>
#include<iostream>
#include<utility>
#include<vector>
using namespace std;

const int N = 27;
int p, q;                     // p: 行数（数字维度），q: 列数（字母维度）
bool st[N][N];                // st[i][j]=true 表示格子(i,j)已被访问
vector<pair<char, int>> path; // 当前搜索路径：first=列字母, second=行号

/*-----8种骑士走法（按输出字典序排列）-----
 * 输出格式为"字母+数字"（如A1B3），字典序优先比较字母（即列），
 * 字母相同时比较数字（即行）。因此dx/dy的排列使得DFS优先尝试
 * 字母更小、数字更小的目标格子。
 *
 * dx[8] = {-2, -2, -1, -1,  1,  1,  2,  2}  // 列（字母）变化
 * dy[8] = {-1,  1, -2,  2, -2,  2, -1,  1}  // 行（数字）变化
 *
 * 对应走法：(Δ列, Δ行) = 列变化量, 行变化量
 * (-2,-1) (-2,+1) (-1,-2) (-1,+2) (+1,-2) (+1,+2) (+2,-1) (+2,+1)
 *
 * 为什么这个顺序能保证字典序最小：
 * - 目标列字母较小的走法排在前面（Δx更负的优先）
 * - 列相同时，目标行数字较小的排在前面（Δy更负的优先）
 *-----*/
int dx[8] = {-2, -2, -1, -1,  1,  1,  2,  2};
int dy[8] = {-1,  1, -2,  2, -2,  2, -1,  1};

/*-----dfs函数分析-----
 * dfs(x, y, cnt)：从格子(x,y)出发，当前已访问cnt个格子（含当前），
 * 尝试完成骑士巡游。
 *
 * 参数说明：
 * - x: 当前列索引（0='A', 1='B', ...）
 * - y: 当前行索引（0=第1行, 1=第2行, ...）
 * - cnt: 已访问的格子数量（含当前格子）
 *
 * 递归分解：
 * - 记录路径：将当前格子（列字母+行号）加入path。
 * - 边界条件：cnt == p*q 时，所有格子均已访问，输出完整路径并返回true。
 * - 递归体：
 *   1. 标记当前格子为已访问（st[x][y] = true）
 *   2. 按字典序遍历8种走法，对每种合法走法（在边界内且未访问）递归
 *   3. 剪枝优化：若某分支dfs返回true，立即向上返回true（不再尝试其他走法）
 *   4. 回溯：若所有走法均失败，取消标记并从路径中移除当前格子
 * -----*/
bool dfs(int x, int y, int cnt)
{
    // 将当前格子加入路径：列字母 + 行号（行号从1开始）
    path.push_back({char(x + 'A'), y + 1});

    // 边界条件：已访问完所有格子
    if (cnt == p * q)
    {
        for (auto a : path)
            cout << a.first << a.second;  // 输出完整巡游路径
        return true;  // 找到解，立即返回（保证字典序最小）
    }

    st[x][y] = true;  // 标记当前格子为已访问

    // 按字典序遍历8种骑士走法
    for (int i = 0; i < 8; i++)
    {
        int a = x + dx[i], b = y + dy[i];

        // 边界检查：目标格子必须在棋盘范围内
        if (a < 0 || a >= q || b < 0 || b >= p)
            continue;
        // 已访问检查：不能重复踩同一个格子
        if (st[a][b])
            continue;
        // 递归尝试，若找到解则立即传播成功信号
        if (dfs(a, b, cnt + 1))
            return true;
    }

    // 回溯：当前格子出发的所有走法均已尝试且失败，恢复状态
    st[x][y] = false;
    path.pop_back();
    return false;
}

int main()
{
    int T;
    cin >> T;

    for (int t = 1; t <= T; t++)
    {
        cout << "#" << t << ":" << endl;
        cin >> p >> q;

        path.clear();
        memset(st, 0, sizeof(st));  // 重置访问标记数组

        bool flag = false;
        // 按字典序遍历所有可能的起点：
        // 外层循环遍历列（字母维度），内层遍历行（数字维度），
        // 保证首先尝试 A1, A2, A3, ... 作为起点
        for (int i = 0; i < q; i++)      // 列（字母）：A, B, C, ...
            for (int j = 0; j < p; j++)  // 行（数字）：1, 2, 3, ...
            {
                if (dfs(i, j, 1))
                {
                    flag = true;
                    break;  // 找到一条路径即停止搜索
                }
            }

        if (!flag)
            cout << "none";  // 所有起点均无法完成巡游

        cout << endl;
    }
}
