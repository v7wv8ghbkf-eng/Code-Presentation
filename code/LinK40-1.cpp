int dx[8] = {-2, -2, -1, -1,  1,  1,  2,  2};
int dy[8] = {-1,  1, -2,  2, -2,  2, -1,  1};

/*-----dfs鍑芥暟鍒嗘瀽-----
 * dfs(x, y, cnt)锛氫粠鏍煎瓙(x,y)鍑哄彂锛屽綋鍓嶅凡璁块棶cnt涓牸瀛愶紙鍚綋鍓嶏級锛? * 灏濊瘯瀹屾垚楠戝＋宸℃父銆? *
 * 鍙傛暟璇存槑锛? * - x: 褰撳墠鍒楃储寮曪紙0='A', 1='B', ...锛? * - y: 褰撳墠琛岀储寮曪紙0=绗?琛? 1=绗?琛? ...锛? * - cnt: 宸茶闂殑鏍煎瓙鏁伴噺锛堝惈褰撳墠鏍煎瓙锛? *
 * 閫掑綊鍒嗚В锛? * - 璁板綍璺緞锛氬皢褰撳墠鏍煎瓙锛堝垪瀛楁瘝+琛屽彿锛夊姞鍏ath銆? * - 杈圭晫鏉′欢锛歝nt == p*q 鏃讹紝鎵€鏈夋牸瀛愬潎宸茶闂紝杈撳嚭瀹屾暣璺緞骞惰繑鍥瀟rue銆? * - 閫掑綊浣擄細
 *   1. 鏍囪褰撳墠鏍煎瓙涓哄凡璁块棶锛坰t[x][y] = true锛? *   2. 鎸夊瓧鍏稿簭閬嶅巻8绉嶈蛋娉曪紝瀵规瘡绉嶅悎娉曡蛋娉曪紙鍦ㄨ竟鐣屽唴涓旀湭璁块棶锛夐€掑綊
 *   3. 鍓灊浼樺寲锛氳嫢鏌愬垎鏀痙fs杩斿洖true锛岀珛鍗冲悜涓婅繑鍥瀟rue锛堜笉鍐嶅皾璇曞叾浠栬蛋娉曪級
 *   4. 鍥炴函锛氳嫢鎵€鏈夎蛋娉曞潎澶辫触锛屽彇娑堟爣璁板苟浠庤矾寰勪腑绉婚櫎褰撳墠鏍煎瓙
 * -----*/
bool dfs(int x, int y, int cnt)
{
    // 灏嗗綋鍓嶆牸瀛愬姞鍏ヨ矾寰勶細鍒楀瓧姣?+ 琛屽彿锛堣鍙蜂粠1寮€濮嬶級
    path.push_back({char(x + 'A'), y + 1});

    // 杈圭晫鏉′欢锛氬凡璁块棶瀹屾墍鏈夋牸瀛?    if (cnt == p * q)
    {
        for (auto a : path)
            cout << a.first << a.second;  // 杈撳嚭瀹屾暣宸℃父璺緞
        return true;  // 鎵惧埌瑙ｏ紝绔嬪嵆杩斿洖锛堜繚璇佸瓧鍏稿簭鏈€灏忥級
    }

    st[x][y] = true;  // 鏍囪褰撳墠鏍煎瓙涓哄凡璁块棶

    // 鎸夊瓧鍏稿簭閬嶅巻8绉嶉獞澹蛋娉?    for (int i = 0; i < 8; i++)
    {
        int a = x + dx[i], b = y + dy[i];

        // 杈圭晫妫€鏌ワ細鐩爣鏍煎瓙蹇呴』鍦ㄦ鐩樿寖鍥村唴
        if (a < 0 || a >= q || b < 0 || b >= p)
            continue;
        // 宸茶闂鏌ワ細涓嶈兘閲嶅韪╁悓涓€涓牸瀛?        if (st[a][b])
            continue;
        // 閫掑綊灏濊瘯锛岃嫢鎵惧埌瑙ｅ垯绔嬪嵆浼犳挱鎴愬姛淇″彿
        if (dfs(a, b, cnt + 1))
            return true;
    }

    // 鍥炴函锛氬綋鍓嶆牸瀛愬嚭鍙戠殑鎵€鏈夎蛋娉曞潎宸插皾璇曚笖澶辫触锛屾仮澶嶇姸鎬?    st[x][y] = false;
    path.pop_back();
    return false;
}

