/*-----题目分析-----
 * 2的幂次方表示：将正整数n表示为2的幂次方的和，且幂次方也要用2的幂次方表示。
 * 例：137 = 2(2(2)+2+2(0))+2(2+2(0))+2(0)
 * 约定：2的0次方表示为2(0)，2的1次方直接写2
 * 输入：n（n<=20000）
 * 输出：符合约定的表示（无空格）
 * 思路：将n分解为若干2^k之和（二进制分解），对每个指数k递归地表示
 *-----题目分析-----*/
#include <iostream>
#include <cstring>
#include <cmath>
using namespace std;

/*-----dfs函数分析-----*/
// dfs：返回整数n的2的幂次方表示字符串
// 递归策略：
//   1. 找到不超过n的最大2^k（即n的最高二进制位）
//   2. 对k递归表示（k=0时返回"2(0)"，k=1时返回"2"，k>1时返回"2("+dfs(k)+")"）
//   3. 若还有剩余（n-2^k > 0），用"+"连接剩余部分的表示
// 递归出口：n==0返回"0"，n==1返回"2(0)"，n==2返回"2"
string dfs(int n)
{
    // 递归出口：处理基础情况
    if (n == 0) return "0";
    if (n == 1) return "2(0)";
    if (n == 2) return "2";

    string res = "";
    int k = 0;
    // 找到不超过n的最大2的幂次：2^k <= n < 2^(k+1)
    while ((1 << (k + 1)) <= n)
    {
        k++;
    }

    // 构造2^k的表示
    if (k == 1)
    {
        // 2^1 直接写 "2"，不需要括号
        res += "2";
    }
    else
    {
        // k>1 时，需要递归表示指数k
        res += "2(" + dfs(k) + ")";
    }

    // 处理剩余部分：n - 2^k
    int remain = n - (1 << k);
    if (remain > 0)
        res += "+" + dfs(remain);   // 递归表示剩余部分

    return res;
}

int main()
{
    int n;
    cin >> n;
    cout << dfs(n);
    return 0;
}