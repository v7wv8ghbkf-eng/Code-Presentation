// 纭澶ц嚧鐨勬暟缁勮寖鍥达紝闃叉鏁扮粍澶皬銆佽竟鐣屽お绱т粠鑰屽彂鐢熻秺鐣?const int N = 1007;

// n绉嶇墿鍝侊紝鑳屽寘瀹归噺涓簃锛堟暟鎹寖鍥?N,V 鈮?1000锛?int n, m;
// 绗琲绉嶇墿鍝佺殑锛歷浣撶Н / w浠峰€硷紙姣忕鐗╁搧鏈夋棤闄愪欢鍙敤锛?int v[N], w[N];
/*-----鐘舵€佽〃绀篺[i][j]-----*/
// 銆愰泦鍚堛€戝鍓峣绉嶇墿鍝併€侀檺瀹氬閲忎负j锛屾墍鏈夊彲鑳界殑鎬讳环鍊?int f[N][N];

int main()
{
    // 杈撳叆骞惰濉厓绱狅紝浠?寮€濮嬫柟渚夸笅鏍囪瀵?    cin >> n >> m;
    for(int i = 1; i <= n; i ++)
    {
        cin >> v[i] >> w[i];
    }

    // 鏋氫妇鐗╁搧绉嶆暟涓庨檺瀹氬閲忥紝閮芥槸鐢卞皯鍒板鏋氫妇
    for(int i = 1; i <= n; i++)
    {
        for(int j = 0; j <= m; j++)
        {
            /*-----闆嗗悎杩愮畻-----*/
            // 瀵瑰墠i绉嶇墿鍝佷笌闄愬畾瀹归噺j鑰岃█锛屾灇涓鹃€夊彇绗琲绉嶇墿鍝佺殑鏁伴噺k锛?            // 鍥犱负姣忕鐗╁搧鏈夋棤闄愪欢锛宬鍙互浠?鍙栧埌 j/v[i]锛堝閲忎笂闄愶級
            // f[i][j] = max{ f[i-1][j - k*v[i]] + k*w[i] }   (0 鈮?k 鈮?j/v[i])

            // k浠?寮€濮嬫灇涓撅細k=0绛変环浜庝笉閫夌i绉嶇墿鍝侊紙f[i-1][j]锛?            for(int k = 0; j >= k * v[i]; k++)
            {
                // 閫塳涓i绉嶇墿鍝侊細鑵惧嚭k*v[i]瀹归噺锛岃幏寰梜*w[i]浠峰€?                // 浠?f[i-1][...]锛堜笂涓€灞傦級杞Щ
                f[i][j] = max(f[i][j], f[i - 1][j - k * v[i]] + k * w[i]);
            }
        }
    }

    // 鏈€缁堟墍闇€瑕佺殑绛旀锛?    // 鏄悓鏃跺瓨鍦╪绉嶇墿鍝?姣忕鏃犻檺浠?鏃讹紝闄愬畾(鑳屽寘)鎬诲閲忎负m锛屾墍鍙栧緱鐨勬€讳环鍊兼渶澶у€?    cout << f[n][m] << endl;
    return 0;
}

