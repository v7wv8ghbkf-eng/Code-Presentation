// 搴忓垪闀垮害
int n;
/*-----鐘舵€佽〃绀篺[i]-----*/
// 銆愰泦鍚堛€戜互绗琲涓暟缁撳熬鐨勬墍鏈変笂鍗囧瓙搴忓垪涓紝鏈€闀跨殑閭ｄ竴涓殑闀垮害
int f[N];
