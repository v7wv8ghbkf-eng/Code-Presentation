const int N = 9;

int g[N][N];                            // 鏁扮嫭妫嬬洏锛?琛ㄧず绌烘牸锛?
/*-----鍗犵敤鏍囪鏁扮粍-----*/
// row[x][t]: 绗瑇琛屼腑鏁板瓧t鏄惁宸茶浣跨敤锛坱鑼冨洿1~9锛屼笅鏍?娴垂涓嶇敤锛?// col[y][t]: 绗瑈鍒椾腑鏁板瓧t鏄惁宸茶浣跨敤
// cell[i][j][t]: 绗?i,j)涓?脳3瀹牸锛坕,j 鈭?{0,1,2}锛変腑鏁板瓧t鏄惁宸茶浣跨敤
