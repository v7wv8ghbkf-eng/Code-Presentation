/*-----题目分析-----
 * 求排列的逆序数：
 *   给定 1~n 的一个排列（n ≤ 100000），求其逆序数。
 *   逆序：若 i < j 且 a[i] > a[j]，则 (a[i], a[j]) 构成一个逆序对。
 *   逆序数 = 所有逆序对的总数。
 *
 * 解题思路（归并排序求逆序数）：
 *   在归并排序的合并阶段统计逆序对。当左子区间元素 nums[x] > 右子区间元素 nums[y] 时，
 *   由于左子区间 [x, mid] 内部已有序，从中点到 x 这段所有元素都 > nums[y]，
 *   因此产生 (mid - x + 1) 个逆序对。
 *
 * 关键性质：
 *   - 归并排序在合并时，左右子区间内部已经有序。
 *   - 当取右子区间元素放入 temp 时，说明它比左子区间所有未处理的元素都小，
 *     这些左区间剩余元素都与它构成逆序对。
 *   - 逆序数可能很大（最大约 n(n-1)/2 ≈ 5×10^9），必须用 long long。
 */
#include <iostream>
using namespace std;

const int N = 100000;

int n;
long long cnt = 0;      // 逆序数计数器，使用 long long 防止溢出
int nums[N], temp[N];   // temp[] 为归并临时数组

/*-----merge_set函数分析-----
 * 功能：对 [l, r] 区间进行归并排序，同时统计该区间内的逆序数。
 *
 * 算法流程：
 *   1. 递归基：l >= r 时区间长度为0或1，没有逆序对，直接返回。
 *   2. 分治：取中点 mid，递归处理左右两个子区间。
 *      （左右子区间内部的逆序对在递归中统计完毕）
 *   3. 合并：双指针 x（左半）、y（右半）扫描：
 *      - 若 nums[x] <= nums[y]：正常合并，不产生逆序对
 *      - 若 nums[x] > nums[y]：nums[y] 与左半区间所有剩余元素
 *        （即 [x, mid]）都构成逆序对，cnt += (mid - x + 1)
 *   4. 将合并后的有序数据写回原数组。
 *
 * 为什么只在取右区间元素时计数？
 *   因为当 nums[x] > nums[y] 时，左区间 [x, mid] 中的元素
 *   在原排列中都位于 nums[y] 之前（索引更小）但值更大，
 *   恰好满足逆序对的定义 (i < j 且 a[i] > a[j])。
 */
void merge_set(int l, int r)
{
    if (l >= r)
        return;  // 递归基：单元素区间无逆序对

    int mid = l + r >> 1;  // 取中点
    int x = l, y = mid + 1;  // x:左子区间指针, y:右子区间指针
    int k = 0;               // temp数组的写入指针

    // 递归处理左右两个子区间（子区间内部的逆序对在递归中统计）
    merge_set(l, mid);
    merge_set(mid + 1, r);

    // 合并两个有序子区间，同时统计跨区间逆序对
    while (x <= mid && y <= r)
    {
        if (nums[x] <= nums[y])
        {
            // 正常情况：左 ≤ 右，不产生逆序对
            temp[k++] = nums[x++];
        }
        else
        {
            /*-----逆序对统计核心-----
             * nums[x] > nums[y]，说明 nums[y] 与左区间 [x, mid] 中
             * 所有剩余元素都构成逆序对——这些元素都在 nums[y] 前面（索引更小）
             * 但值都比 nums[y] 大。
             */
            cnt += mid - x + 1;  // 一次性统计 mid - x + 1 个逆序对
            temp[k++] = nums[y++];
        }
    }
    // 处理左子区间剩余元素（这些元素比右子区间所有元素都大，但索引在前，不产生新的逆序对）
    while (x <= mid)
    {
        temp[k++] = nums[x++];
    }
    // 处理右子区间剩余元素（此时左子区间已空，不会产生新的逆序对）
    while (y <= r)
    {
        temp[k++] = nums[y++];
    }
    // 将合并后的有序数据写回原数组 [l, r] 区间
    for (int i = l, j = 0; i <= r; i++, j++)
    {
        nums[i] = temp[j];
    }
    return;
}

int main()
{
    scanf("%d", &n);
    for (int i = 0; i < n; i++)
    {
        scanf("%d", &nums[i]);
    }

    merge_set(0, n - 1);  // 归并排序并统计逆序数
    cout << cnt;           // 输出逆序数

    return 0;
}
