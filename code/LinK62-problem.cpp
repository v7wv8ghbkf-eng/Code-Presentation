#include <iostream>
using namespace std;

// 纭澶ц嚧鐨勬暟缁勮寖鍥达紝闃叉鏁扮粍澶皬銆佽竟鐣屽お绱т粠鑰屽彂鐢熻秺鐣?const int N = 1007;

// 涓夎褰㈢殑琛屾暟
int n;
// w[i][j]绗琲琛岀j鍒楃殑鏁板瓧
int w[N][N];
/*-----鐘舵€佽〃绀篺[i][j]-----*/
// 銆愰泦鍚堛€戜粠(i,j)鍑哄彂鍒拌揪搴曢儴鑳借幏寰楃殑鏈€澶у拰
int f[N][N];

int main()
{
    // 杈撳叆涓夎褰紙琛屼笅鏍囦粠1寮€濮嬶紝绗琲琛屾湁i涓暟瀛楋級
    cin >> n;
    for (int i = 1; i <= n; i++)
        for (int j = 1; j <= i; j++)
            cin >> w[i][j];

    /*----- 鐘舵€佸垵濮嬪寲锛氫笁瑙掑舰搴曡竟 -----*/
    // f[n][x] 灏辨槸浠庢渶搴曞眰鍑哄彂锛屽彧缁忚繃杩欎竴涓偣锛屽拰灏辨槸瀹冭嚜韬殑鏁板€?    for (int x = 1; x <= n; x++)
        f[n][x] = w[n][x];

    /*----- 鑷簳鍚戜笂閫掓帹 -----*/
    // 浠庡€掓暟绗簩琛屽線涓婃帹锛屾瘡琛岄€愬垪璁＄畻
    // f[i][j] = 褰撳墠浣嶇疆鐨勬暟瀛?+ 涓嬫柟涓や釜浣嶇疆涓緝澶х殑閭ｄ釜
    for(int i = n - 1; i > 0; i--)
    {
        for(int j = 1; j <= i; j++)
        {
            // 浠?i,j)鍑哄彂锛氬彲浠ヨ蛋鍚戞涓嬫柟(i+1,j)鎴栧彸涓嬫柟(i+1,j+1)
            // 閫夋嫨涓嬫柟涓ゆ潯璺緞涓緝澶х殑锛屽姞涓婂綋鍓嶄綅缃殑鏁板瓧
            f[i][j] = max(f[i + 1][j], f[i + 1][j + 1]) + w[i][j];
        }
    }

    // 鏈€缁堢瓟妗堬細浠庨《鐐?1,1)鍑哄彂鎵€鑾峰緱鐨勬渶澶ц矾寰勫拰
    cout << f[1][1] << endl;
    return 0;
}
