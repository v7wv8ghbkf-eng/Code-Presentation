#include <iostream>
using namespace std;

// 确认大致的数组范围，防止数组太小、边界太紧从而发生越界
const int N = 1007;

// 三角形的行数
int n;
// w[i][j]第i行第j列的数字
int w[N][N];
/*-----状态表示f[i][j]-----*/
// 【集合】从(i,j)出发到达底部能获得的最大和
int f[N][N];

int main()
{
    // 输入三角形（行下标从1开始，第i行有i个数字）
    cin >> n;
    for (int i = 1; i <= n; i++)
        for (int j = 1; j <= i; j++)
            cin >> w[i][j];

    /*----- 状态初始化：三角形底边 -----*/
    // f[n][x] 就是从最底层出发，只经过这一个点，和就是它自身的数值
    for (int x = 1; x <= n; x++)
        f[n][x] = w[n][x];

    /*----- 自底向上递推 -----*/
    // 从倒数第二行往上推，每行逐列计算
    // f[i][j] = 当前位置的数字 + 下方两个位置中较大的那个
    for(int i = n - 1; i > 0; i--)
    {
        for(int j = 1; j <= i; j++)
        {
            // 从(i,j)出发：可以走向正下方(i+1,j)或右下方(i+1,j+1)
            // 选择下方两条路径中较大的，加上当前位置的数字
            f[i][j] = max(f[i + 1][j], f[i + 1][j + 1]) + w[i][j];
        }
    }

    // 最终答案：从顶点(1,1)出发所获得的最大路径和
    cout << f[1][1] << endl;
    return 0;
}
