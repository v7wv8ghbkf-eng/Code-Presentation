#include <iostream>
#include <algorithm>
using namespace std;

// 纭澶ц嚧鐨勬暟缁勮寖鍥达紝闃叉鏁扮粍澶皬銆佽竟鐣屽お绱т粠鑰屽彂鐢熻秺鐣?const int N = 110;
// 瀹氫箟鏃犵┓澶у父閲忥紝鐢ㄤ簬鍒濆鍖栨渶灏忚垂鐢ㄧ殑姣旇緝
const int INF = 1e9;

// 姝ｆ柟褰㈢殑瀹藉害N
int s;
// w[i][j]绗琲琛岀j鍒楁柟鏍肩殑璐圭敤锛沠[i][j]浠庡乏涓婅鍒拌揪(i,j)鐨勬渶灏忔€昏垂鐢?int w[N][N], f[N][N];

int main()
{
    // 杈撳叆姝ｆ柟褰㈢殑瀹藉害
    cin >> s;

    // 杈撳叆姣忎釜鏂规牸鐨勮垂鐢紝涓嬫爣浠?寮€濮?    for (int i = 1; i <= s; i++)
        for (int j = 1; j <= s; j++)
            cin >> w[i][j];

    /*----- 鐘舵€侀€掓帹锛氶€愯閫愬垪璁＄畻鏈€灏忚垂鐢?-----*/
    // 棰樼洰瑕佹眰蹇呴』鍦?2N-1)鍗曚綅鏃堕棿鍐呯┛瓒婏紝杩欐剰鍛崇潃鍙兘鍚戝彸鎴栧悜涓嬭蛋
    // 锛堝鏋滃線鍥炶蛋浼氳秴鏃讹級锛屾墍浠ヤ笌"鎽樿姳鐢?鎬濊矾绫讳技锛屼絾姹傜殑鏄渶灏忓€?    for (int i = 1; i <= s; i++)
    {
        for (int j = 1; j <= s; j++)
        {
            // 璧风偣鐗规畩澶勭悊锛氭病鏈?浠庡摢杈规潵"鐨勯€夋嫨
            if (i == 1 && j == 1)
                f[i][j] = w[i][j];
            else
            {
                // 鍏堝垵濮嬪寲涓烘棤绌峰ぇ锛屽啀鐢╩in閫夊嚭杈冨皬璺緞
                f[i][j] = INF;
                // 濡傛灉涓婃柟鏈夋牸瀛愶紝鑰冭檻浠庝笂杈规潵
                if (i > 1)
                    f[i][j] = min(f[i][j], f[i - 1][j] + w[i][j]);
                // 濡傛灉宸︽柟鏈夋牸瀛愶紝鑰冭檻浠庡乏杈规潵
                if (j > 1)
                    f[i][j] = min(f[i][j], f[i][j - 1] + w[i][j]);
            }
        }
    }

    // 鏈€缁堢瓟妗堬細浠庡乏涓婅(1,1)鍒板彸涓嬭(s,s)鐨勬渶灏忔€昏垂鐢?    cout << f[s][s] << endl;
    return 0;
}
