/*-----题目分析-----
 * 在无限大的方格命运矩阵上，从第0行出发，每次只能向下、左、右三个
 * 方向移动一格，走过的格子不可重复访问。求恰好走n步的不同路径总数。
 *
 * 本质：在二维网格上统计"不重复访问"的路径数量，移动方向受限为
 *       左、右、下三个方向（无向上），且不能走回头路。
 *
 * 解法：DFS + 回溯。
 * - fates[][] 标记已访问的格子
 * - 对当前位置，尝试三种走法，递归计算剩余步数的方案数
 * - 回溯时取消标记，使不同分支可以独立搜索
 *
 * 起点选择：由于n <= 20，最坏情况全向左（或全向右）需要20列空间，
 * 因此将起点放在(0, N/2)即第0行第35列，N=70提供左右各35列的缓冲。
 *-----*/

#include <iostream>
using namespace std;

const int N = 70;
bool fates[N][N];  // 标记矩阵：fates[i][j]=true表示格子(i,j)已被踩过

/* 三种移动方向与坐标变动的关系：
 * k=0: 向左 —— (0, -1)
 * k=1: 向右 —— (0, +1)
 * k=2: 向下 —— (+1, 0)
 * 注意：没有向上移动，因为只能向下、左、右三个方向走。 */
int dx[3] = {0, 0, 1}, dy[3] = {-1, 1, 0};

/*-----dfs函数分析-----
 * dfs(i, j, n)：从格子(i,j)出发，恰好走n步的不同路径数。
 *
 * 递归分解：
 * - 边界条件：n == 0 时，无需再走，仅有"原地不动"这1种方案。
 * - 递归体：
 *   1. 标记当前格子为已访问（fates[i][j] = true）
 *   2. 遍历三种走法（左、右、下），对每种走法的目标格子：
 *      - 若目标格子未被访问过，则递归计算走n-1步的路径数并累加
 *   3. 回溯：取消当前格子的标记（fates[i][j] = false），
 *      使其他递归分支可以重新访问该格子。
 *
 * 返回值使用long long：n=20时结果可达54608393，超出int范围。
 *-----*/
long long dfs(int i, int j, int n)
{
    if (n == 0)
        return 1;  // 边界：剩余0步，只有1种方案

    long long res = 0;  // 累加所有合法走法的路径数

    fates[i][j] = true;         // 标记当前格子已被踩入
    for (int k = 0; k < 3; k++) // 尝试三种走法：左、右、下
    {
        int x = i + dx[k], y = j + dy[k];
        // 若目标格子未被访问过，则可以向该方向走
        if (fates[x][y] == 0)
            res += dfs(x, y, n - 1);  // 递归：走完这一步后还剩n-1步
    }

    fates[i][j] = false;  // 回溯：恢复标记，供其他路径分支使用
    return res;
}

int main()
{
    int x;
    cin >> x;
    // 从第0行中间列出发，走x步
    cout << dfs(0, N / 2, x) << endl;
    return 0;
}
