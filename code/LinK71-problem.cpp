#include <iostream>
using namespace std;

// 确认大致的数组范围，防止数组太小、边界太紧从而发生越界
const int N = 1010;

// 序列长度
int n;
/*-----状态表示f[i]-----*/
// 【集合】以第i个数结尾的所有上升子序列中，最长的那一个的长度
int f[N];
// a[i]原序列的第i个数值
int a[N];

int main()
{
    // 输入序列长度和序列元素，下标从0开始
    cin >> n;
    for (int x = 0; x < n; x++)
        cin >> a[x];

    /*----- 状态递推：O(N²) -----*/
    // res存储最终答案（全局最长长度）
    // 注意：不一定以最后一个元素结尾的就是最长的，需要遍历所有f[i]取最大
    int res = 0;
    for(int i = 0; i < n; i++)
    {
        // 对每个位置i，以自身为起点的子序列长度至少为1
        f[i] = 1;

        // 遍历i之前的所有位置j，尝试将a[i]接在以a[j]结尾的子序列后面
        for(int j = 0; j < i; j ++)
        {
            // 如果a[j] < a[i]，说明满足严格递增，可以接上
            if(a[j] < a[i])
            {
                // 以a[j]结尾的长度+1（算上a[i]自己）
                f[i] = max(f[i], f[j] + 1);
            }
        }
        // 每计算完一个f[i]，更新全局最大值
        res = max(res, f[i]);
    }

    // 最终答案：整个序列中最长严格递增子序列的长度
    cout << res << endl;
    return 0;
}
