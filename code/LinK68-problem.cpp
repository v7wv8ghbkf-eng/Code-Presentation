#include <iostream>
using namespace std;

// 确认大致的数组范围，防止数组太小、边界太紧从而发生越界
const int N = 1010;

// num种物品和一个容量是V的背包
int num, V;
// 第i种物品的：v体积 / w价值 / s数量
// s=-1表示01背包（只能用1次）；s=0表示完全背包（无限次）；s>0表示多重背包（最多s次）
int v[N], w[N], s[N];
/*-----状态表示f[i][j]-----*/
// 【集合】对前i种物品、限定容量为j，所有可能的总价值
int f[N][N];

int main()
{
    // 输入并装填元素，从1开始方便下标观察
    cin >> num >> V;
    for (int i = 1; i <= num; i++)
    {
        cin >> v[i] >> w[i] >> s[i];
    }

    // 枚举物品种数与限定容量，都是由少到多枚举
    for (int i = 1; i <= num; i++)
    {
        for (int j = 0; j <= V; j++)
        {
            /*-----集合运算-----*/
            // 无论哪种背包类型，都可以选择不拿第i种物品
            f[i][j] = f[i - 1][j];

            // ----- 情况一：01背包 (s[i] == -1) -----
            // 第i种物品只能用1次，选或不选
            // 从 f[i-1][j-v[i]]（上一层）转移，保证每件只用一次
            if (s[i] == -1)
            {
                if (j >= v[i])
                    f[i][j] = max(f[i][j], f[i - 1][j - v[i]] + w[i]);
            }

            // ----- 情况二：完全背包 (s[i] == 0) -----
            // 第i种物品可以用无限次，枚举选取数量k（朴素做法）
            // f[i][j] = max{ f[i-1][j - k*v[i]] + k*w[i] }  (0 ≤ k ≤ j/v[i])
            if (s[i] == 0)
            {
                for (int k = 0; j >= k * v[i]; k++)
                {
                    f[i][j] = max(f[i][j], f[i - 1][j - k * v[i]] + k * w[i]);
                }
            }

            // ----- 情况三：多重背包 (s[i] > 0) -----
            // 第i种物品最多用s[i]次，枚举选取数量k（朴素做法）
            // f[i][j] = max{ f[i-1][j - k*v[i]] + k*w[i] }  (0 ≤ k ≤ s[i], k*v[i] ≤ j)
            if (s[i] > 0)
            {
                for (int k = 0; k <= s[i] && j >= k * v[i]; k++)
                {
                    f[i][j] = max(f[i][j], f[i - 1][j - k * v[i]] + k * w[i]);
                }
            }
        }
    }

    // 最终所需要的答案：
    // 是同时存在num种物品(混合类型)时，限定(背包)总容量为V，所取得的总价值最大值
    cout << f[num][V] << endl;
    return 0;
}

/*
 * ===== 完全背包优化：将枚举k改为O(1)转移 =====
 * 完全背包部分的三重循环可以优化为O(N*V)：
 *   将 s[i]==0 分支的 for(k) 循环替换为：
 *     if (j >= v[i])
 *         f[i][j] = max(f[i][j], f[i][j - v[i]] + w[i]);
 * 关键：用 f[i][j-v[i]]（本层）而非 f[i-1][j-v[i]]（上层），
 * 因为完全背包选了第i种之后还能继续选第i种。
 *
 * ===== 多重背包优化：二进制拆分 =====
 * 多重背包部分(s[i]>0)可进一步用二进制拆分优化（参见LinK66的优化版本），
 * 将s[i]件按1,2,4,8,...打包后做01背包，复杂度从O(N*V*max_s)降为O(N*V*log(max_s))。
 */
