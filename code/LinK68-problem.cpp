#include <iostream>
using namespace std;

// 纭澶ц嚧鐨勬暟缁勮寖鍥达紝闃叉鏁扮粍澶皬銆佽竟鐣屽お绱т粠鑰屽彂鐢熻秺鐣?const int N = 1010;

// num绉嶇墿鍝佸拰涓€涓閲忔槸V鐨勮儗鍖?int num, V;
// 绗琲绉嶇墿鍝佺殑锛歷浣撶Н / w浠峰€?/ s鏁伴噺
// s=-1琛ㄧず01鑳屽寘锛堝彧鑳界敤1娆★級锛泂=0琛ㄧず瀹屽叏鑳屽寘锛堟棤闄愭锛夛紱s>0琛ㄧず澶氶噸鑳屽寘锛堟渶澶歴娆★級
int v[N], w[N], s[N];
/*-----鐘舵€佽〃绀篺[i][j]-----*/
// 銆愰泦鍚堛€戝鍓峣绉嶇墿鍝併€侀檺瀹氬閲忎负j锛屾墍鏈夊彲鑳界殑鎬讳环鍊?int f[N][N];

int main()
{
    // 杈撳叆骞惰濉厓绱狅紝浠?寮€濮嬫柟渚夸笅鏍囪瀵?    cin >> num >> V;
    for (int i = 1; i <= num; i++)
    {
        cin >> v[i] >> w[i] >> s[i];
    }

    // 鏋氫妇鐗╁搧绉嶆暟涓庨檺瀹氬閲忥紝閮芥槸鐢卞皯鍒板鏋氫妇
    for (int i = 1; i <= num; i++)
    {
        for (int j = 0; j <= V; j++)
        {
            /*-----闆嗗悎杩愮畻-----*/
            // 鏃犺鍝鑳屽寘绫诲瀷锛岄兘鍙互閫夋嫨涓嶆嬁绗琲绉嶇墿鍝?            f[i][j] = f[i - 1][j];

            // ----- 鎯呭喌涓€锛?1鑳屽寘 (s[i] == -1) -----
            // 绗琲绉嶇墿鍝佸彧鑳界敤1娆★紝閫夋垨涓嶉€?            // 浠?f[i-1][j-v[i]]锛堜笂涓€灞傦級杞Щ锛屼繚璇佹瘡浠跺彧鐢ㄤ竴娆?            if (s[i] == -1)
            {
                if (j >= v[i])
                    f[i][j] = max(f[i][j], f[i - 1][j - v[i]] + w[i]);
            }

            // ----- 鎯呭喌浜岋細瀹屽叏鑳屽寘 (s[i] == 0) -----
            // 绗琲绉嶇墿鍝佸彲浠ョ敤鏃犻檺娆★紝鏋氫妇閫夊彇鏁伴噺k锛堟湸绱犲仛娉曪級
            // f[i][j] = max{ f[i-1][j - k*v[i]] + k*w[i] }  (0 鈮?k 鈮?j/v[i])
            if (s[i] == 0)
            {
                for (int k = 0; j >= k * v[i]; k++)
                {
                    f[i][j] = max(f[i][j], f[i - 1][j - k * v[i]] + k * w[i]);
                }
            }

            // ----- 鎯呭喌涓夛細澶氶噸鑳屽寘 (s[i] > 0) -----
            // 绗琲绉嶇墿鍝佹渶澶氱敤s[i]娆★紝鏋氫妇閫夊彇鏁伴噺k锛堟湸绱犲仛娉曪級
            // f[i][j] = max{ f[i-1][j - k*v[i]] + k*w[i] }  (0 鈮?k 鈮?s[i], k*v[i] 鈮?j)
            if (s[i] > 0)
            {
                for (int k = 0; k <= s[i] && j >= k * v[i]; k++)
                {
                    f[i][j] = max(f[i][j], f[i - 1][j - k * v[i]] + k * w[i]);
                }
            }
        }
    }

    // 鏈€缁堟墍闇€瑕佺殑绛旀锛?    // 鏄悓鏃跺瓨鍦╪um绉嶇墿鍝?娣峰悎绫诲瀷)鏃讹紝闄愬畾(鑳屽寘)鎬诲閲忎负V锛屾墍鍙栧緱鐨勬€讳环鍊兼渶澶у€?    cout << f[num][V] << endl;
    return 0;
}

