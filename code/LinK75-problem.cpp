#include<iostream>
using namespace std;

// 确认大致的数组范围，防止数组太小、边界太紧从而发生越界
const int N = 1010;

// 字符串A长度为n，字符串B长度为m
int n, m;
// A和B是两个字符串（从下标1开始存储，方便与f数组对齐）
char A[N], B[N];
/*-----状态表示f[i][j]-----*/
// 【集合】所有由A的前i个字符和B的前j个字符构成的公共子序列中，最长的那一个的长度
int f[N][N];

int main()
{
    // 输入字符串长度，以及两个字符串（从下标1开始存储）
    cin >> n >> m;
    cin >> A + 1 >> B + 1;

    // 枚举字符串A和B的前缀长度，由短到长递推
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            /*-----集合运算-----*/
            // 对f[i][j]而言，有两种大情况：
            // 1. A[i] == B[j]：这两个字符可以配对
            //    → 在f[i-1][j-1]的基础上+1（将A[i]和B[j]加入公共子序列）
            // 2. A[i] != B[j]：至少有一个字符不在最优解中
            //    → 取 max(不看A[i]的情况, 不看B[j]的情况)

            if(A[i] == B[j])
            {
                // 两字符相等：直接从前缀(i-1,j-1)继承并长度+1
                f[i][j] = f[i - 1][j - 1] + 1;
            }
            else
            {
                // 两字符不等：取"去掉A[i]"和"去掉B[j]"两种方案中较大的
                f[i][j] = max(f[i - 1][j], f[i][j - 1]);
            }
        }
    }

    // 最终所需要的答案：
    // A的前n个字符与B的前m个字符的最长公共子序列长度
    cout << f[n][m] << endl;
    return 0;
}
