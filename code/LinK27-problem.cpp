#include <iostream>
using namespace std;

const int N = 1000010;
int q[N];  // 鍏ㄥ眬鏁扮粍锛屽瓨鍌ㄥ緟鎺掑簭鏁版嵁

/*-----quick_sort鍑芥暟鍒嗘瀽-----
 * 鍔熻兘锛氬鏁扮粍 nums 鍦?[left, right] 鍖洪棿鍐呰繘琛屽揩閫熸帓搴忥紙鍗囧簭锛夈€? *
 * 绠楁硶娴佺▼锛圚oare 鍒掑垎锛夛細
 *   1. 閫掑綊缁堟鏉′欢锛歭eft >= right锛屽尯闂翠负绌烘垨鍗曞厓绱狅紝鏃犻渶鎺掑簭銆? *   2. 閫夊彇鍩哄噯鍊?x = nums[(left + right) / 2]锛堝尯闂翠腑闂翠綅缃殑鍏冪礌锛夈€? *   3. 鍙屾寚閽?i锛堜粠宸﹀悜鍙筹級銆乯锛堜粠鍙冲悜宸︼級鎵弿锛? *      - i 璺宠繃鎵€鏈夊皬浜?x 鐨勫厓绱狅紙閬囧埌 >= x 鐨勫厓绱犲仠姝級
 *      - j 璺宠繃鎵€鏈夊ぇ浜?x 鐨勫厓绱狅紙閬囧埌 <= x 鐨勫厓绱犲仠姝級
 *      - 鑻?i < j 鍒欎氦鎹?nums[i] 鍜?nums[j]锛岀户缁壂鎻? *   4. 鎸囬拡浜ら敊鍚庯紝宸﹀瓙鍖洪棿 [left, j] 涓殑鍏冪礌鍧?<= 鍙冲瓙鍖洪棿 [j+1, right] 涓殑鍏冪礌锛? *      閫掑綊瀵逛袱涓瓙鍖洪棿鍒嗗埆鎺掑簭銆? *
 * 娉ㄦ剰锛氭澶?while(i<j) + do-while 缁撴瀯淇濊瘉鎸囬拡涓€瀹氫細绉诲姩锛? *   閬垮厤鍙栧埌鏋佺鍩哄噯鍊兼椂鍑虹幇姝诲惊鐜€? */
void quick_sort(int nums[], int left, int right)
{
    if (left >= right)
        return;  // 鍖洪棿澶у皬涓?鎴?锛屽凡缁忔湁搴?
    int i = left - 1, j = right + 1;
    int x = nums[left + right >> 1];  // 鍙栧尯闂翠腑闂翠綅缃殑鍏冪礌浣滀负鍩哄噯

    while (i < j)
    {
        // i 鍙崇Щ锛岀洿鍒版壘鍒?>= 鍩哄噯鐨勫厓绱?        do
        {
            i++;
        } while (nums[i] < x);

        // j 宸︾Щ锛岀洿鍒版壘鍒?<= 鍩哄噯鐨勫厓绱?        do
        {
            j--;
        } while (nums[j] > x);

        // 鑻?i < j锛屼氦鎹袱涓?绔欓敊浣嶇疆"鐨勫厓绱?        if (i < j)
            swap(nums[i], nums[j]);
    }

    // 鍒掑垎瀹屾垚鍚庯紝[left, j] 涓殑鍏冪礌 鈮?[j+1, right] 涓殑鍏冪礌
    // 閫掑綊澶勭悊宸﹀彸涓や釜瀛愬尯闂?    quick_sort(nums, left, j);
    quick_sort(nums, j + 1, right);
}

int main()
{
    int n;
    scanf("%d" , &n);
    for (int i = 0; i < n; i++)
    {
        scanf("%d" , &q[i]);
    }

    quick_sort(q, 0, n - 1);

    for (int i = 0; i < n; i++)
    {
        printf("%d " , q[i]);
    }
    printf("\n");

    return 0;
}
