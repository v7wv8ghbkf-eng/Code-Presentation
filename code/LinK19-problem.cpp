#include <iostream>
#include <vector>
using namespace std;

int n;
vector<int> path;       // 褰撳墠瀛愰泦璺緞

/*-----dfs鍑芥暟鍒嗘瀽-----*/
// dfs锛氭灇涓句粠start寮€濮嬬殑鎵€鏈夊瓙闆嗭紝褰撳墠璺緞path涓繚瀛樺凡閫夌殑鏁?// 閫掑綊绛栫暐锛氭瘡涓妭鐐瑰厛杈撳嚭褰撳墠璺緞锛堝嵆涓€涓瓙闆嗭級锛屽啀鏋氫妇涓嬩竴涓€夌殑鏁?// 鍏抽敭璁捐锛氭瘡娆¤繘鍏fs鍏堣緭鍑猴紝淇濊瘉绌洪泦涔熻兘杈撳嚭锛涚劧鍚庝粠start寰€鍚庨€夋暟锛?//          淇濊瘉瀛愰泦鍐呭厓绱犲崌搴忥紝鍚屾椂閬垮厤閲嶅锛堝{1,2}鍜寋2,1}鍙緭鍑轰竴娆★級
void dfs(int start) {
    // 灏嗗綋鍓嶈矾寰勪腑鐨勫瓙闆嗚緭鍑猴紙姣忎釜鑺傜偣閮芥槸涓€涓悎娉曞瓙闆嗭紝鍖呮嫭绌洪泦锛?    for (int i = 0; i < (int)path.size(); i++)
    {
        if (i > 0) cout << " ";
        cout << path[i];
    }
    cout << endl;

    // 妯悜鏋氫妇锛氫粠start寮€濮嬩緷娆″皾璇曢€夋嫨姣忎釜鏁板姞鍏ュ瓙闆?    // i浠巗tart寮€濮嬩繚璇佷簡鍗囧簭锛岄伩鍏嶉噸澶嶅瓙闆?    for (int i = start; i <= n; i++)
    {
        path.push_back(i);      // 閫夋嫨i鍔犲叆褰撳墠瀛愰泦
        dfs(i + 1);             // 绔栧悜娣卞叆锛氫笅涓€涓暟浠巌+1寮€濮嬮€夛紙淇濊瘉鍗囧簭锛?        path.pop_back();        // 鍥炴函锛氭挙閿€閫夋嫨锛屾í鍚戝皾璇曚笅涓€涓暟
    }
}

int main() {
    cin >> n;
    dfs(1);
    return 0;
}