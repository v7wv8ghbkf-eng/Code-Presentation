#include<cmath>
using namespace std;

int V, N;

/*------dfs鍑芥暟鍒嗘瀽-----*/
// dfs:瀵圭粰瀹氱殑灞傛暟N锛屾€讳綋绉疺;杈撳嚭鏈€灏忚〃闈㈢НS
/*
鏈涓庨粍閲戣泲绯曚汉椹殑鍖哄埆鍦ㄤ簬涓茶鍫嗗彔銆佸苟琛屽垎鍓?
鍒囪泲绯曟椂鍊欏姣忎竴涓灇涓惧嚭鏉ョ殑宸﹀彸/涓婁笅涓ゅ潡锛岄兘杩樺瓨鍦ㄦ棤鏁扮殑鍒囨硶锛堝洜涓鸿繕瀛樺湪妯珫鍒囨硶涓嶅悓+瑕佹眰鍧楁暟涓嶅悓锛?
浣嗚泲绯曞灏嗗叾鍒嗕负涓婁笅涓ゅ眰鏄病鏈夋剰涔夌殑锛屽洜涓衡€滃眰鏁板垎閰嶁€濅笌鈥滃崐寰勪笌楂樺害鐨勯€掑鈥濆叧鑱斾笉澶?
dfs蹇呯劧鍖呮嫭r銆乭鐨勯檺鍒跺苟涓旇兘澶熼€氳繃dfs鏈韩浼犻€掞紝鍚屾椂涔熻兘鍖呮嫭v銆乶鐨勭‘瀹?
鎵€浠ヨ泲绯曞闂鏄熀浜庡鐞嗗畬鏈眰+缁х画杩涜涓嬩竴灞傛潵杩唬鐨?
*/

int dfs(int v, int n, int last_r, int last_h)
{
    // 濡傛灉灞傛暟涓?锛岃鏄庝笉闇€瑕佺户缁€掑綊浜嗭紱濡傛灉v == 0锛岄偅涔堟湰灞傚氨鏄暐閮芥病鏈夛紱濡傛灉杩樻湁鍓╀笅鐨勪綋绉病鐢ㄥ畬
    if (n == 0)
        return v == 0 ? 0 : INT_MAX;

    // 瀵规湰灞傜殑r銆乭杩涜鏋氫妇 
    // 鐢变簬鏄嚜涓嬭€屼笂鏋氫妇鐨勶紝鏄痜or(涓婇檺;涓嬮檺;閫掑噺)
    
    int best = INT_MAX;
    // r涓轰粈涔堝繀鐒跺ぇ浜庡眰鏁皀?鍥犱负濡傛灉r == n锛岄偅涔堟帴涓嬫潵鐨勬瘡涓€灞傞兘鏄眰鍗婂緞鏈€灏忓€?锛屽鏋渞灏忎簬n锛岄偅涔堝墿涓嬬殑灞備腑浼氬瓨鍦ㄥ皬鏁版垨鑰?锛屾槸涓嶅彲鍙栫殑
    // h鐨勪笅闄愪篃鏄悓鐞?
    // r鐨勪笂闄愭槸涓婁竴灞傚崐寰勯檺鍒讹紙浼犲弬浼氬噺1锛屾墍浠ュ彲浠ョ瓑浜庯級鍜屾湰灞備綋绉紑鏂硅繖涓よ€呬腑鏇村皬鐨勯偅涓?
    // h鐨勪笂闄愭槸瀵瑰凡缁忛€夌殑r锛屽鏋滄伆濂借兘鎾戞弧v鐨勯珮搴?
    // 涔嬫墍浠ヤ笂闄愰渶瑕佸彇min锛屾槸鍥犱负濡傛灉鍚庨潰鐨勫鍔犻檺鍒跺ぇ浜巐ast浼氬嚭闂锛涜€屽鏋滃鍔犻檺鍒舵洿灏忥紝閭ｄ箞灏卞繀椤荤敤杩欎釜澶栧姞闄愬埗
    for (int r = min(last_r, (int)sqrt(v)); r >= n; r--)
    {
        for (int h = min(last_h, v / (r * r)); h >= n; h--)
        {
            int cur = 2 * r * h;
            int sub =  dfs(v - r * r * h, n - 1, r - 1, h - 1);
            if(sub != INT_MAX)
            best = min(best, cur + sub);
        }
    }
    return best;
}

int main()
{
    cin >> V >> N;
    cout << dfs(V, N, (int)sqrt(V), V + 1) << endl;;
    return 0;
}